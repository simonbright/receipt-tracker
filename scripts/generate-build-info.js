import { readFileSync, writeFileSync } from 'fs';
import { execSync } from 'child_process';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

function getCommit() {
  const fromEnv = process.env.RENDER_GIT_COMMIT || process.env.GITHUB_SHA;
  if (fromEnv) return fromEnv.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
  } catch {
    return 'local';
  }
}

const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const buildInfo = {
  version: pkg.version,
  commit: getCommit(),
  builtAt: new Date().toISOString(),
};

const tsContent = `// Generated by scripts/generate-build-info.js — do not edit
export const buildInfo = ${JSON.stringify(buildInfo, null, 2)} as const;
`;

writeFileSync(path.join(root, 'src/build-info.ts'), tsContent);
writeFileSync(path.join(root, 'public/build-info.json'), `${JSON.stringify(buildInfo, null, 2)}\n`);

console.log('Build info:', buildInfo);
